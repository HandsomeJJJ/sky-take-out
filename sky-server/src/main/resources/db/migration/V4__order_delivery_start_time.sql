-- =================================================================-----------
-- V4：给"开始派送"单独留一个时间字段
--
-- 原来派送中订单的超时收尾是拿 order_time（下单时间）判定"超过 60 分钟"的：
-- 用户下单 40 分钟后商家才接单派送，那这单只剩下 20 分钟的派送窗口，
-- 到点就被系统置成"已完成"——钱记进营业额，餐可能还在路上。
--
-- 判定超时应该用"什么时候进入派送"，所以这个事实必须被记下来。
-- 老数据没有这个字段值，扫描时用 COALESCE(delivery_start_time, order_time) 回退，
-- 不会因为历史行为空而永远扫不到。
-- ============================================================================

ALTER TABLE orders
    ADD COLUMN delivery_start_time DATETIME DEFAULT NULL COMMENT '开始派送时间（派送动作发生的时间，不是送达时间）';

-- 超时收尾任务按"派送中 + 开始派送时间"扫描，没有这个索引就是每分钟一次的全表扫
CREATE INDEX idx_orders_status_delivery_start
    ON orders (status, delivery_start_time);
